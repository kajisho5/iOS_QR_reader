#!/usr/bin/env python3
"""Generate SeijitsuQR/Core/Localization/L10n.swift from Localizable.xcstrings.

Every UI string lives in the String Catalog; code refers to it only through the
generated `L10n` members, so a missing or misspelled key fails to compile.

Usage:
  python3 tools/gen_l10n.py          # regenerate
  python3 tools/gen_l10n.py --check  # exit 1 if the checked-in file is stale (CI)
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CATALOG = ROOT / "SeijitsuQR/Resources/Localizable.xcstrings"
OUTPUT = ROOT / "SeijitsuQR/Core/Localization/L10n.swift"
SPEC = re.compile(r"%(?:\d+\$)?(lld|ld|d|@)")


def member_name(key: str) -> str:
    parts = re.split(r"[.\-_]", key)
    name = parts[0] + "".join(p[:1].upper() + p[1:] for p in parts[1:])
    if not re.match(r"^[a-z][A-Za-z0-9]*$", name):
        raise SystemExit(f"invalid key for a Swift identifier: {key}")
    return name


def render(catalog: dict) -> str:
    source = catalog["sourceLanguage"]
    lines = [
        "// Generated by tools/gen_l10n.py from Localizable.xcstrings. Do not edit by hand.",
        "import Foundation",
        "",
        "enum L10n {",
    ]
    keys = sorted(catalog["strings"])
    for key in keys:
        value = catalog["strings"][key]["localizations"][source]["stringUnit"]["value"]
        specs = SPEC.findall(value)
        name = member_name(key)
        if not specs:
            lines.append(f'    static var {name}: String {{ String(localized: "{key}") }}')
        else:
            params = []
            for i, spec in enumerate(specs, 1):
                params.append((f"_ p{i}", "String" if spec == "@" else "Int"))
            signature = ", ".join(f"{label}: {kind}" for label, kind in params)
            args = ", ".join(f"p{i}" for i in range(1, len(params) + 1))
            lines.append(f"    static func {name}({signature}) -> String {{")
            lines.append(f'        String(format: String(localized: "{key}"), {args})')
            lines.append("    }")
    lines.append("")
    lines.append("    /// Every key in the catalog, used by tests to verify each one resolves.")
    lines.append("    static let allKeys: [String] = [")
    for key in keys:
        lines.append(f'        "{key}",')
    lines.append("    ]")
    lines.append("}")
    return "\n".join(lines) + "\n"


def main() -> int:
    catalog = json.loads(CATALOG.read_text(encoding="utf-8"))
    generated = render(catalog)
    if "--check" in sys.argv:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if current != generated:
            print("L10n.swift is out of date. Run: python3 tools/gen_l10n.py", file=sys.stderr)
            return 1
        print("L10n.swift is up to date.")
        return 0
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(generated, encoding="utf-8")
    print(f"Wrote {OUTPUT.relative_to(ROOT)} ({len(catalog['strings'])} keys)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
